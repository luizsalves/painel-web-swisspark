USE [corpore_neu]

DECLARE @DataInicial DATE = '2025-12-01';
DECLARE @DataFinal   DATE = '2025-12-31';

WITH LANCAMENTOS AS (
    SELECT
        CONVERT(char(7), A.[DATA], 126) AS [ANO_MES],
        A.[DATA],
        UPPER(LTRIM(RTRIM(E.[NOME]))) AS [EMPRESA],
        A.[CODCOLIGADA],
        COALESCE(CT.[REDUZIDO], '-') AS [REDUZIDO],
        CASE WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] ELSE A.[CREDITO] END AS [CODCONTA],
        A.[CODFILIAL],
        A.[COMPLEMENTO],
        A.[DOCUMENTO],
        A.[IDLANCAMENTO] AS [ID_LANCAMENTO],
        A.[IDPARTIDA]    AS [ID_PARTIDA],
        A.[USUARIO],
        CASE 
            WHEN A.[DEBITO] IS NOT NULL AND CAST(A.[DEBITO] AS VARCHAR(50)) LIKE '1.%' THEN A.[VALOR]
            WHEN A.[DEBITO] IS NOT NULL THEN (-1) * A.[VALOR]
            ELSE 0
        END AS [DEBITOS],
        CASE 
            WHEN A.[CREDITO] IS NOT NULL AND CAST(A.[CREDITO] AS VARCHAR(50)) LIKE '1.%' THEN (-1) * A.[VALOR]
            WHEN A.[CREDITO] IS NOT NULL THEN A.[VALOR]
            ELSE 0
        END AS [CREDITOS]
    FROM [CPARTIDA] A
    LEFT JOIN [GFILIAL] E
        ON E.[CODCOLIGADA] = A.[CODCOLIGADA] AND E.[CODFILIAL] = A.[CODFILIAL]
    LEFT JOIN [CCONTA] CT
        ON CT.[CODCOLIGADA] = A.[CODCOLIGADA]
       AND CT.[CODCONTA] = (CASE WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] ELSE A.[CREDITO] END)
    WHERE LTRIM(RTRIM(CAST(A.[CODCOLIGADA] AS VARCHAR(20)))) = '18'
      AND UPPER(LTRIM(RTRIM(E.[NOME]))) = 'SWISS PARK CAIEIRAS INCORPORADORA SPE LTDA SCP'
      AND LTRIM(RTRIM(CAST(A.[CODFILIAL] AS VARCHAR(20)))) = '2'
      AND (A.[DEBITO] = '2.1.1.01.01.0001' OR A.[CREDITO] = '2.1.1.01.01.0001')
      AND A.[DATA] >= @DataInicial AND A.[DATA] <= @DataFinal
),
ANTERIOR AS (
    SELECT 
        CASE WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] ELSE A.[CREDITO] END AS [CODCONTA],
        SUM(
            CASE 
                WHEN A.[DEBITO] IS NOT NULL AND CAST(A.[DEBITO] AS VARCHAR(50)) LIKE '1.%' THEN A.[VALOR]
                WHEN A.[DEBITO] IS NOT NULL THEN (-1) * A.[VALOR]
                WHEN A.[CREDITO] IS NOT NULL AND CAST(A.[CREDITO] AS VARCHAR(50)) LIKE '1.%' THEN (-1) * A.[VALOR]
                WHEN A.[CREDITO] IS NOT NULL THEN A.[VALOR]
                ELSE 0
            END
        ) AS [ANTERIOR]
    FROM [CPARTIDA] A
    WHERE LTRIM(RTRIM(CAST(A.[CODCOLIGADA] AS VARCHAR(20)))) = '18'
      AND LTRIM(RTRIM(CAST(A.[CODFILIAL] AS VARCHAR(20)))) = '2'
      AND (A.[DEBITO] = '2.1.1.01.01.0001' OR A.[CREDITO] = '2.1.1.01.01.0001')
      AND A.[DATA] < @DataInicial
    GROUP BY CASE WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] ELSE A.[CREDITO] END
)
SELECT 
    L.[ANO_MES], L.[DATA], L.[EMPRESA], L.[CODCOLIGADA], L.[REDUZIDO],
    L.[CODCONTA], L.[CODFILIAL], L.[COMPLEMENTO], L.[DOCUMENTO], L.[ID_LANCAMENTO], L.[ID_PARTIDA],
    L.[USUARIO], L.[DEBITOS], L.[CREDITOS],
    CAST(NULL AS NUMERIC(18,4)) AS [SALDO_RAZAO]
FROM LANCAMENTOS L

UNION ALL

SELECT 
    L.[ANO_MES], NULL, MAX(L.[EMPRESA]), MAX(L.[CODCOLIGADA]), MAX(L.[REDUZIDO]),
    L.[CODCONTA], MAX(L.[CODFILIAL]), 'SALDO DO RAZAO (COMPOSICAO)', NULL, NULL, NULL,
    NULL, SUM(L.[DEBITOS]), SUM(L.[CREDITOS]),
    COALESCE(MAX(A.[ANTERIOR]), 0) + SUM(L.[DEBITOS]) + SUM(L.[CREDITOS]) AS [SALDO_RAZAO]
FROM LANCAMENTOS L
LEFT JOIN ANTERIOR A ON A.[CODCONTA] = L.[CODCONTA]
GROUP BY L.[ANO_MES], L.[CODCONTA]












