CREATE OR REPLACE FUNCTION public.fc_razao(datainicial date, datafinal date, containicial character varying, contafinal character varying, coligada integer, bancodedados integer)
 RETURNS TABLE(idbancodados integer, data date, idpartida integer, complemento character varying, conta character varying, valordebito numeric, valorcredito numeric, valordebitoanterior numeric, valorcreditoanterior numeric)


SELECT 
		A."DATA",
		CONVERT(char(7), DATA, 126) AS ANO_MES,
		A."IDPARTIDA",
		A."COMPLEMENTO",
		CASE WHEN A."DEBITO" IS NOT NULL THEN A."DEBITO"
			ELSE A."CREDITO"
		END AS CONTA,
		CASE WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '1.%' THEN A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '2.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '3.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '4.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '5.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '6.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '7.%' THEN (-1) * A."VALOR"
			 WHEN A."DEBITO" IS NOT NULL AND CAST(A."DEBITO" AS VARCHAR(50)) LIKE '8.%' THEN (-1) * A."VALOR"
			ELSE 0
		END AS VALORDEBITO,
		CASE WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '1.%' THEN (-1) * A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '2.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '3.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '4.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '5.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '6.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '7.%' THEN A."VALOR"
			 WHEN A."CREDITO" IS NOT NULL AND CAST(A."CREDITO" AS VARCHAR(50)) LIKE '8.%' THEN A."VALOR"
			ELSE 0
		END AS VALORCREDITO,
		CASE WHEN A."VALORDEBITOANTERIOR" IS NULL THEN 0 ELSE A."VALORDEBITOANTERIOR" END AS VALORDEBITOANTERIOR,
		CASE WHEN A."VALORCREDITOANTERIOR" IS NULL THEN 0 ELSE A."VALORCREDITOANTERIOR" END AS VALORCREDITOANTERIOR
FROM "CPARTIDA" A
WHERE CONVERT(char(7), DATA, 126) = '2025-12'
AND A."CODCOLIGADA" = 1 
and A.CODFILIAL = 
and 
WHERE X.CONTA BETWEEN CONTAINICIAL AND CONTAFINAL
ORDER BY 1,5,2,3
