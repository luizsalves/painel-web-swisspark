DECLARE @BANCO       SYSNAME     = 'corpore_neu';
DECLARE @CODCOLIGADA INT         = 18;
DECLARE @CODFILIAL   INT         = 3;
DECLARE @DATA        DATE        = '2026-08-01';
DECLARE @CODCONTA    VARCHAR(50) = '2.1.1.03.01.0002';

DECLARE @SQL NVARCHAR(MAX);

SET @SQL = CAST(N'
SELECT 
    CONVERT(char(7), A.[DATA], 126) AS [ANOMES], 
    A.[DATA], 
    UPPER(LTRIM(RTRIM(E.[NOME]))) AS [EMPRESA], 
    A.[CODCOLIGADA], 
    COALESCE(CT.[REDUZIDO], ''-'') AS [REDUZIDO], 

    CASE 
        WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] 
        ELSE A.[CREDITO] 
    END AS [CODCONTA], 

    A.[CODFILIAL], 
    LTRIM(RTRIM(E.[NOMEFANTASIA])) AS [NOMEFANTASIA], 
    A.[COMPLEMENTO], 
    A.[DOCUMENTO], 
    A.[IDLANCAMENTO], 
    A.[IDPARTIDA], 
    A.[USUARIO], 

    CASE 
        WHEN A.[DEBITO] IS NOT NULL
             AND A.[DEBITO] LIKE ''1%''
            THEN A.[VALOR] 

        WHEN A.[DEBITO] IS NOT NULL 
            THEN (-1) * A.[VALOR] 

        ELSE 0 
    END AS [DEBITOS], 

    CASE 
        WHEN A.[CREDITO] IS NOT NULL
             AND A.[CREDITO] LIKE ''1%''
            THEN (-1) * A.[VALOR] 

        WHEN A.[CREDITO] IS NOT NULL 
            THEN A.[VALOR] 

        ELSE 0 
    END AS [CREDITOS] 

FROM ' AS NVARCHAR(MAX))
+ QUOTENAME(@BANCO) + N'.dbo.[CPARTIDA] A WITH (NOLOCK)

LEFT JOIN ' + QUOTENAME(@BANCO) + N'.dbo.[GFILIAL] E WITH (NOLOCK) 
    ON E.[CODCOLIGADA] = A.[CODCOLIGADA] 
   AND E.[CODFILIAL] = A.[CODFILIAL] 

LEFT JOIN ' + QUOTENAME(@BANCO) + N'.dbo.[CCONTA] CT WITH (NOLOCK) 
    ON CT.[CODCOLIGADA] = A.[CODCOLIGADA] 
   AND CT.[CODCONTA] =
        CASE 
            WHEN A.[DEBITO] IS NOT NULL THEN A.[DEBITO] 
            ELSE A.[CREDITO] 
        END

WHERE A.[CODCOLIGADA] = @P_CODCOLIGADA
  AND A.[CODFILIAL] = @P_CODFILIAL
  AND A.[DATA] >= @P_DATA
  AND A.[DATA] < DATEADD(MONTH, 1, @P_DATA)
  AND (
        A.[DEBITO] = @P_CODCONTA
        OR A.[CREDITO] = @P_CODCONTA
      );
';

EXEC sp_executesql
    @SQL,

    N'@P_CODCOLIGADA INT,
      @P_CODFILIAL INT,
      @P_DATA DATE,
      @P_CODCONTA VARCHAR(50)',

    @P_CODCOLIGADA = @CODCOLIGADA,
    @P_CODFILIAL   = @CODFILIAL,
    @P_DATA        = @DATA,
    @P_CODCONTA    = @CODCONTA;




